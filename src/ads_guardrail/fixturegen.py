def _entity(platform: Platform, account: str, s: Spec) -> Entity:
    return Entity(platform=platform, account_id=account, entity_id=s.entity_id, name=s.name,
                  daily_budget_micros=usd(s.budget), bid_micros=usd(s.bid) if s.bid else None,
                  budget_shared=s.shared_budget, target_cpa_micros=usd(s.target_cpa) if s.target_cpa else None,
                  target_roas=s.target_roas, ref=s.strategy)


def _money(micros: int) -> str:
    return f"{micros / MICROS:.2f}"


def generate(out_dir: Path, seed: int = SEED) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    ents = [_entity(Platform.GOOGLE_ADS, GOOGLE_CUSTOMER, s) for s in GOOGLE] + \
           [_entity(Platform.META, META_ACCOUNT, s) for s in META]
    account = InMemoryAdAccount(ents)
    curves = {e.key: s.curve for e, s in zip(ents, GOOGLE + META)}
    sim = MarketSimulator(account, curves, seed=seed)
    start = HISTORY_END - timedelta(days=HISTORY_DAYS - 1)
    for i in range(HISTORY_DAYS):
        sim.step(start + timedelta(days=i))
    metrics = account.fetch_metrics(start, HISTORY_END)
    specs = {s.entity_id: s for s in GOOGLE + META}

    # ---- Google Ads: searchStream responses ----
    g_entities = [{"results": [{
        "campaign": {
            "resourceName": f"customers/{GOOGLE_CUSTOMER}/campaigns/{s.entity_id}",
            "id": s.entity_id, "name": s.name, "status": "ENABLED",
            "biddingStrategyType": s.strategy,
            "biddingStrategySystemStatus": "LEARNING_NEW" if s.learning_days else "ENABLED",
            **({"targetCpa": {"targetCpaMicros": str(usd(s.bid))}} if s.strategy == "TARGET_CPA" and s.bid else {}),
            **({"maximizeConversions": {"targetCpaMicros": str(usd(s.bid))}} if s.strategy == "MAXIMIZE_CONVERSIONS" and s.bid else {}),
        },
        "campaignBudget": {
            "resourceName": f"customers/{GOOGLE_CUSTOMER}/campaignBudgets/{int(s.entity_id) + 9_000_000_000}",
            "amountMicros": str(usd(s.budget)), "explicitlyShared": s.shared_budget,
        },
    } for s in GOOGLE], "fieldMask": "campaign.id,campaign.name,...", "requestId": "synthetic-entities"}]
    g_metrics = [{"results": [{
        "campaign": {"resourceName": f"customers/{GOOGLE_CUSTOMER}/campaigns/{m.entity_id}", "id": m.entity_id},
        "segments": {"date": m.day.isoformat()},
        "metrics": {"costMicros": str(m.spend_micros), "impressions": str(m.impressions), "clicks": str(m.clicks),
                    "conversions": m.conversions, "conversionsValue": 0.0},
    } for m in metrics if m.platform is Platform.GOOGLE_ADS], "requestId": "synthetic-metrics"}]
    g_targets = {s.entity_id: {"target_cpa_micros": usd(s.target_cpa)} for s in GOOGLE if s.target_cpa}

    # ---- Meta: Graph API pages ----
    adsets = [{
        "id": s.entity_id, "name": s.name, "daily_budget": str(int(s.budget * 100)),
        "bid_strategy": s.strategy, "effective_status": "ACTIVE",
        **({"bid_amount": str(int(s.bid * 100))} if s.bid else {}),
        "learning_stage_info": {"status": "LEARNING" if s.learning_days else "SUCCESS"},
    } for s in META]
    meta_rows = [{
        "adset_id": m.entity_id, "adset_name": specs[m.entity_id].name, "spend": _money(m.spend_micros),
        "impressions": str(m.impressions), "clicks": str(m.clicks),
        "actions": [{"action_type": "offsite_conversion.fb_pixel_purchase", "value": str(int(m.conversions))},
                    {"action_type": "link_click", "value": str(m.clicks)}],
        "action_values": [{"action_type": "offsite_conversion.fb_pixel_purchase", "value": _money(m.conversion_value_micros)}],
        "date_start": m.day.isoformat(), "date_stop": m.day.isoformat(),
    } for m in metrics if m.platform is Platform.META]
    page = 500
    insights = [{"data": meta_rows[i:i + page],
                 "paging": {"cursors": {"before": f"c{i}", "after": f"c{i + page}"},
                            **({"next": f"https://graph.facebook.com/v23.0/{META_ACCOUNT}/insights?after=c{i + page}"} if i + page < len(meta_rows) else {})}}
                for i in range(0, len(meta_rows), page)]
    m_targets = {s.entity_id: {"target_roas": s.target_roas} for s in META if s.target_roas}

    sim_params = {
        "curves": {k: asdict(c) for k, c in curves.items()},
        "learning_days": {e.key: specs[e.entity_id].learning_days for e in ents if specs[e.entity_id].learning_days},
    }
    manifest = {
        "_synthetic": True, "label": LABEL, "seed": seed,
        "history_start": start.isoformat(), "history_end": HISTORY_END.isoformat(), "days": HISTORY_DAYS,
        "accounts": [
            {"platform": "google_ads", "account_id": GOOGLE_CUSTOMER, "name": "Demo Home Services (synthetic lead gen)", "entities": len(GOOGLE)},
            {"platform": "meta", "account_id": META_ACCOUNT, "name": "Demo Outdoor Goods (synthetic ecommerce)", "entities": len(META)},
        ],
    }
    files = {
        "manifest.json": manifest,
        "google_ads/campaigns.searchStream.json": g_entities,
        "google_ads/metrics.searchStream.json": g_metrics,
        "google_ads/targets.json": {"_synthetic": True, "targets": g_targets},
        "meta/adsets.pages.json": [{"data": adsets, "paging": {"cursors": {"before": "a0", "after": "a1"}}}],
        "meta/insights.pages.json": insights,
        "meta/targets.json": {"_synthetic": True, "targets": m_targets},
        "sim/hidden_curves.json": {"_synthetic": True, "note": "Hidden response curves for the SIMULATOR only. The policy never reads this.", **sim_params},
    }
    written = {}
    for rel, obj in files.items():
        p = out_dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(obj, indent=1, sort_keys=False) + "\n")
        written[rel] = p
    (out_dir / "README.md").write_text(
        "# Fixtures (SYNTHETIC)\n\n" + LABEL + "\n\n"
        "Google Ads files are searchStream JSON responses. Meta files are Graph API pages.\n"
        "`sim/hidden_curves.json` is read only by the simulator, never by the policy.\n"
        "Regenerate with `python -m ads_guardrail.fixturegen`.\n")
    return written


DEFAULT_DIR = Path(__file__).parent / "fixtures"

if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DIR
    for rel in generate(target):
        print(f"wrote {target / rel}")
